# ISO/IEC 18004 Table 7: data capacity in bits, derived from the two tables above by
# the identity data = total - error correction, then converted from codewords to bits.
MAX_BITS: dict[int, dict[str, int]] = {
    version: {
        ec: (
            TOTAL_CODEWORDS[version]
            - ECC_BLOCKS[version][ec][0] * ECC_BLOCKS[version][ec][1]
        ) * 8
        for ec in EC_LEVELS
    }
    for version in range(1, 41)
}

# ISO/IEC 18004 §7.4: the character-count indicator width in bits for each mode, per
# version group. Version groups are 1-9, 10-26 and 27-40, in that order.
_CHAR_COUNT_BITS: dict[str, tuple[int, int, int]] = {
    "numeric": (10, 12, 14),
    "alphanumeric": (9, 11, 13),
    "byte": (8, 16, 16),
}

# ISO/IEC 18004 §7.4: characters per bit in each mode, as an exact integer ratio (characters, bits)
# — 3 digits per 10 bits, 2 alphanumeric characters per 11 bits, 1 byte per 8 bits. Integer
# arithmetic keeps a boundary length exact; a float ratio would make it depend on binary rounding.
_PAYLOAD_RATIO: dict[str, tuple[int, int]] = {
    "numeric": (3, 10),
    "alphanumeric": (2, 11),
    "byte": (1, 8),
}

# ISO/IEC 18004 §7.4: every mode's indicator is 4 bits and precedes the character-count indicator.
_MODE_INDICATOR_BITS: int = 4


def capacity_bits(version: int, ec: str) -> int:
    """Return the data capacity, in bits, of a symbol at `version` and `ec`.

    Guarantees the ISO/IEC 18004 Table 7 figure, ``(TOTAL_CODEWORDS[version] - blocks *
    ecc_per_block) * 8``.

    Raises:
        ValueError: `version` is not an integer in 1..40, or `ec` is not one of `EC_LEVELS`.
    """
    _require_version(version)
    _require_ec(ec)
    return MAX_BITS[version][ec]


def data_codewords(version: int, ec: str) -> int:
    """Return the number of data codewords of a symbol at `version` and `ec`.

    Guarantees ``capacity_bits(version, ec) // 8``.

    Raises:
        ValueError: `version` is outside 1..40, or `ec` is not one of `EC_LEVELS`.
    """
    _require_version(version)
    _require_ec(ec)
    blocks, ecc_per_block = ECC_BLOCKS[version][ec]
    return TOTAL_CODEWORDS[version] - blocks * ecc_per_block


def max_payload_bytes(version: int, ec: str, mode: str) -> int:
    """Return the largest payload a symbol at `version` and `ec` holds in `mode`.

    The unit follows the mode: **characters** for "numeric" and "alphanumeric", **bytes** for
    "byte". The 4-bit mode indicator and the mode's character-count indicator are subtracted from
    the data capacity before the per-character bit cost is applied (ISO/IEC 18004 §7.4).

    Raises:
        ValueError: `version` is outside 1..40, `ec` is not one of `EC_LEVELS`, or `mode` is not one
            of `MODES`; the message names the offending value.
    """
    _require_version(version)
    _require_ec(ec)
    _require_mode(mode)
    available = (
        capacity_bits(version, ec) - _MODE_INDICATOR_BITS - _char_count_bits(version, mode)
    )
    characters, bits = _PAYLOAD_RATIO[mode]
    return (available * characters) // bits


def minimal_version(length: int, ec: str, mode: str) -> int | None:
    """Return the smallest Version 1-40 that holds `length` characters or bytes.

    `length` is a character count in "numeric" and "alphanumeric" mode and a byte count in "byte"
    mode, and the scan runs ascending over ``range(1, 41)``.

    Returns: ``None`` when the payload exceeds even Version 40, rather than a clamped 40, so a
    caller can tell "does not fit at all" from "does not fit at this version".

    Raises:
        ValueError: `length` is not a non-negative integer, `ec` or `mode` is outside its set.
    """
    _require_ec(ec)
    _require_mode(mode)
    if isinstance(length, bool) or not isinstance(length, int) or length < 0:
        raise ValueError(f"length must be a non-negative integer, got {length!r}")
    for version in range(1, 41):
        if max_payload_bytes(version, ec, mode) >= length:
            return version
    return None


def truncation_keeps_version(length: int, window: int, ec: str) -> bool:
    """Return whether cutting a `length`-byte payload back to `window` bytes keeps its version.

    The single home of the ``truncated_payload`` predicate, so the shortening target and the corpus
    check that proves it observable are one rule. Both lengths are measured in "byte" mode, the most
    expensive way to carry a character, so the measurement can only be conservative. The level is an
    argument because the injection is specified at the *requested* level while cascade containment
    holds only at the level the symbol is encoded at.

    Returns: ``True`` when both lengths select the same byte-mode Version at `ec`, ``False`` when
    either overflows even Version 40; a `window` of 0 is legal.

    Raises:
        ValueError: `length` or `window` is not a non-negative integer, or `ec` is not a level.
    """
    window_version = minimal_version(window, ec, "byte")
    payload_version = minimal_version(length, ec, "byte")
    if window_version is None or payload_version is None:
        return False
    return window_version == payload_version


def _version_group(version: int) -> int:
    """Return the ISO/IEC 18004 §7.4 version group index: 0 for 1-9, 1 for 10-26, 2 for 27-40."""
    if version <= 9:
        return 0
    if version <= 26:
        return 1
    return 2


def _char_count_bits(version: int, mode: str) -> int:
    """Return the width in bits of `mode`'s character-count indicator at `version`."""
    return _CHAR_COUNT_BITS[mode][_version_group(version)]


def _require_version(version: int) -> None:
    """Raise ValueError unless `version` is an integer, not a bool, in 1..40."""
    if (
        isinstance(version, bool)
        or not isinstance(version, int)
        or not 1 <= version <= 40
    ):
        raise ValueError(f"version must be an integer in 1..40, got {version!r}")


def _require_ec(ec: str) -> None:
    """Raise ValueError unless `ec` is one of `EC_LEVELS`."""
    if ec not in EC_LEVELS:
        raise ValueError(f"ec must be one of 'L', 'M', 'Q', 'H', got {ec!r}")


def _require_mode(mode: str) -> None:
    """Raise ValueError unless `mode` is one of `MODES`."""
    if mode not in MODES:
        raise ValueError(
            f"mode must be one of 'numeric', 'alphanumeric', 'byte', got {mode!r}"
        )
